"""Run the tool for real and commit what it printed.

A README that quotes invented output is a README that drifts. This runs the real command
against the real database and writes what came back, exit codes included, so the block in
the documentation is a transcript rather than a description.

Regenerated by `make bench` rather than by `make verify`. The timing lines move between
runs, so putting this in the gate would leave uncommitted changes behind every time the
gate ran, and a gate that dirties the working tree is one people stop reading the output
of. Everything else in the transcript - balances, attempt counts, exit codes - is fixed by
the default seed.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "cli-output.md"

INVOCATIONS = [
    ("A handler with no memory, half the acknowledgements lost",
     ["--handler", "naive", "--ack-loss", "0.5", "--messages", "4000"]),
    ("The same delivery, with an idempotency ledger",
     ["--handler", "idempotent", "--ack-loss", "0.5", "--messages", "4000"]),
    ("A scenario that cannot produce a trustworthy number",
     ["--ack-loss", "1.0"]),
]

PREAMBLE = (
    "Generated by `tools/capture_cli.py`, which runs the real command against a real "
    "PostgreSQL and records what came back. Regenerated by `make bench`; the timing "
    "lines are the only part that moves between runs."
)


def main() -> None:
    sections = ["# Captured output", "", PREAMBLE, ""]
    for title, args in INVOCATIONS:
        result = subprocess.run(
            ["retry-amplification", *args],
            cwd=ROOT, capture_output=True, text=True, check=False,
        )
        body = (result.stdout + result.stderr).rstrip()
        sections += [
            f"## {title}", "",
            "```console",
            f"$ retry-amplification {' '.join(args)}",
            body,
            "$ echo $?", str(result.returncode),
            "```", "",
        ]
        print(f"  captured `{' '.join(args)}` -> exit {result.returncode}")

    OUT.write_text("\n".join(sections))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
